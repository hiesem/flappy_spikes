/// PRD-2.3 §15.2 the source of `tuning_defaults.dart` for [defs] (one line
/// per key).
String renderDefaultsFile(List<TuningDef> defs) {
  final b = StringBuffer(_head);
  for (final d in defs) {
    b.writeln(
      "  TuningDef('${d.key}', TuningType.${d.type.name}, "
      '${renderValue(d.type, d.value)}, ${_str(d.section)}, ${_str(d.doc)}),',
    );
  }
  b.writeln('];');
  return b.toString();
}

/// A default as a canonical Dart literal.
String renderValue(TuningType type, Object v) => switch (type) {
  TuningType.decimal => _double((v as num).toDouble()),
  TuningType.integer => '${(v as num).toInt()}',
  TuningType.boolean => '$v',
  _ => _json(v),
};

String _double(double v) => v == v.roundToDouble() && v.abs() < 1e15
    ? '${v.toInt()}.0'
    : '$v';

String _json(Object? v) {
  if (v is List) return '[${v.map(_json).join(', ')}]';
  if (v is Map) {
    return '{${v.entries.map((e) => '${_str(e.key as String)}: ${_json(e.value)}').join(', ')}}';
  }
  if (v is double && v == v.roundToDouble()) return '${v.toInt()}';
  return '$v';
}

String _str(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

/// PRD-2.3 §15.3 the key table of `docs/p23/TUNING.md` (key, type, default,
/// section, description), generated from [defs].
String renderKeyTable(List<TuningDef> defs) {
  final b = StringBuffer()
    ..writeln('| Key | Type | Default | Section | What |')
    ..writeln('|---|---|---|---|---|');
  for (final d in defs) {
    final v = d.type.encode(d.value).replaceAll('|', r'\|');
    b.writeln(
      '| `${d.key}` | ${d.type.name} | `$v` | §${d.section} | '
      '${d.doc.replaceAll('|', r'\|')} |',
    );
  }
  return b.toString();
}

/// Replaces the text between [start] and [end] markers in [doc] with
/// [body] (markers kept). Returns null when the markers are missing.
String? replaceBetween(String doc, String start, String end, String body) {
  final a = doc.indexOf(start);
  final z = doc.indexOf(end);
  if (a < 0 || z < a) return null;
  return '${doc.substring(0, a + start.length)}\n$body${doc.substring(z)}';
}
