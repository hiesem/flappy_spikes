/// PRD-2.3 §15.5 the export / import code of `tool/tuning_sync.dart` (pure
/// Dart, so the round trip is unit-tested): `tuning_defaults.dart` ⇄ the
/// Remote Config template JSON.
library;

import 'dart:convert';

import 'tuning_types.dart';

/// PRD-2.3 §15.5 `export`: the Remote Config template for [defs] — one
/// parameter group per key group, each key with its default (as the
/// console's string), its value type and "§section doc" as description.
Map<String, Object> exportTemplate(List<TuningDef> defs) {
  final groups = <String, Map<String, Object>>{};
  for (final d in defs) {
    final g = groups.putIfAbsent(d.group, () => <String, Object>{});
    var desc = '§${d.section} ${d.doc}';
    if (desc.length > 256) desc = desc.substring(0, 256);
    g[d.key] = {
      'defaultValue': {'value': d.type.encode(d.value)},
      'description': desc,
      'valueType': d.type.remoteType,
    };
  }
  return {
    'parameterGroups': {
      for (final e in groups.entries)
        e.key: {
          'description': 'PRD-2.3 §15.3 group ${e.key}_',
          'parameters': e.value,
        },
    },
  };
}

/// The template as the JSON text written to
/// `docs/p23/remote_config_template.json`.
String exportTemplateJson(List<TuningDef> defs) =>
    '${const JsonEncoder.withIndent('  ').convert(exportTemplate(defs))}\n';

/// PRD-2.3 §15.5 the console's value strings in [template] (a Remote
/// Config template as the REST API returns it, or as [exportTemplate]
/// writes it): top-level parameters and the parameters of every group.
/// Conditional values are ignored; `useInAppDefault` keeps the default.
Map<String, String> templateValues(Map<String, dynamic> template) {
  final out = <String, String>{};
  void take(Map<String, dynamic>? params) {
    if (params == null) return;
    for (final e in params.entries) {
      final p = e.value;
      if (p is! Map) continue;
      final dv = p['defaultValue'];
      if (dv is! Map) continue;
      if (dv['useInAppDefault'] == true) continue;
      final v = dv['value'];
      if (v is String) out[e.key] = v;
    }
  }

  take((template['parameters'] as Map?)?.cast<String, dynamic>());
  final groups = template['parameterGroups'];
  if (groups is Map) {
    for (final g in groups.values) {
      if (g is Map) {
        take((g['parameters'] as Map?)?.cast<String, dynamic>());
      }
    }
  }
  return out;
}

/// The result of [importDefs].
class ImportResult {
  ImportResult(this.defs, this.changed, this.rejected, this.unknown);

  /// The new defaults (same keys and order as before).
  final List<TuningDef> defs;

  /// Keys whose default changed.
  final List<String> changed;

  /// Keys whose console value did not parse (default kept).
  final List<String> rejected;

  /// Console keys the app does not know (ignored).
  final List<String> unknown;
}

/// PRD-2.3 §15.5 `import`: [values] (from [templateValues]) over [defs].
/// Same keys, same order; a value that does not parse keeps the default.
ImportResult importDefs(List<TuningDef> defs, Map<String, String> values) {
  final changed = <String>[], rejected = <String>[];
  final out = <TuningDef>[];
  for (final d in defs) {
    final raw = values[d.key];
    if (raw == null) {
      out.add(d);
      continue;
    }
    final v = d.type.parse(raw, d.value);
    if (v == null) {
      rejected.add(d.key);
      out.add(d);
      continue;
    }
    if (renderValue(d.type, v) != renderValue(d.type, d.value)) {
      changed.add(d.key);
    }
    out.add(TuningDef(d.key, d.type, v, d.section, d.doc));
  }
  final known = {for (final d in defs) d.key};
  final unknown = [
    for (final k in values.keys)
      if (!known.contains(k)) k,
  ];
  return ImportResult(out, changed, rejected, unknown);
}

