#!/usr/bin/env python3
"""PRD-2.2 §22.2: write lib/game/sound_durations.g.dart.

Reads every file in assets/audio (sound effects and loops; the music files
are skipped) with ffprobe and writes a const Dart table
`file -> (duration ms, file size bytes)`. SoundService stops each one-shot
play after that length + 100 ms (Android SoundPool cannot report a duration).

Run from the flappy_spikes root whenever a sound changes:

    python3 -I tool/gen_sound_durations.py

test/p22/s22_sound_durations_test.dart fails when the table is stale.
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
AUDIO = ROOT / "assets" / "audio"
OUT = ROOT / "lib" / "game" / "sound_durations.g.dart"
# The music files are skipped (PRD-2.3 §16.3: the OGG loop plays on Android
# and Linux, the MP3 stays for iOS).
MUSIC = {"HappyBeat_8-Bit_Retro_Game_Loop.mp3", "HappyBeat_loop_56bars.ogg"}


def duration_ms(path: pathlib.Path) -> int:
    out = subprocess.run(
        [
            "ffprobe", "-v", "error", "-show_entries", "format=duration",
            "-of", "json", str(path),
        ],
        check=True, capture_output=True, text=True,
    ).stdout
    return round(float(json.loads(out)["format"]["duration"]) * 1000)


def main() -> int:
    rows = []
    for f in sorted(AUDIO.iterdir()):
        if not f.is_file() or f.name in MUSIC:
            continue
        if f.suffix.lower() not in (".mp3", ".wav", ".ogg"):
            continue
        rows.append((f.name, duration_ms(f), f.stat().st_size))
    lines = [
        "// GENERATED by tool/gen_sound_durations.py (PRD-2.2 §22.2). Do not edit.",
        "// Regenerate: python3 -I tool/gen_sound_durations.py",
        "",
        "/// Every sound file in assets/audio (the music excluded):",
        "/// file -> (length in ms, file size in bytes).",
        "const Map<String, (int, int)> kSoundDurations = {",
    ]
    lines += [f"  '{n}': ({ms}, {size})," for n, ms, size in rows]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(rows)} entries to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
