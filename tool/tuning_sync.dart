// PRD-2.3 §15.5 remote tuning export / import.
//
//   dart run tool/tuning_sync.dart export
//       lib/run/config/tuning_defaults.dart → docs/p23/remote_config_template.json
//       (and the key table in docs/p23/TUNING.md).
//   dart run tool/tuning_sync.dart import [--from <template.json>] [--project <id>] [--dry-run]
//       The console's Remote Config template (REST API, signed in with the
//       owner's `gcloud`; or a saved template with --from) → rewrites
//       lib/run/config/tuning_defaults.dart. Review the diff and run
//       `flutter test` (the autopilot gate included) before it ships.
//   dart run tool/tuning_sync.dart format
//       Rewrites tuning_defaults.dart in its canonical form (after a key was
//       added by hand).
//
// Run from the app root (flappy_spikes/). Pure Dart: no Flutter needed.

import 'dart:convert';
import 'dart:io';

import 'package:flappy_spikes/run/config/tuning_codegen.dart';
import 'package:flappy_spikes/run/config/tuning_defaults.dart';
import 'package:flappy_spikes/run/config/tuning_types.dart';

const _defaultsPath = 'lib/run/config/tuning_defaults.dart';
const _templatePath = 'docs/p23/remote_config_template.json';
const _docPath = 'docs/p23/TUNING.md';
const _keysStart = '<!-- KEYS:START (generated by tool/tuning_sync.dart export) -->';
const _keysEnd = '<!-- KEYS:END -->';
const _defaultProject = 'flappy-spikes-a2b55';

Future<void> main(List<String> args) async {
  if (args.isEmpty) return _usage();
  final rest = args.sublist(1);
  switch (args.first) {
    case 'export':
      _export(kTuningDefaults);
    case 'format':
      File(_defaultsPath).writeAsStringSync(renderDefaultsFile(kTuningDefaults));
      stdout.writeln('formatted $_defaultsPath (${kTuningDefaults.length} keys)');
    case 'import':
      await _import(rest);
    default:
      _usage();
  }
}

void _usage() {
  stderr.writeln(
    'usage: dart run tool/tuning_sync.dart export | format | '
    'import [--from <template.json>] [--project <id>] [--dry-run]',
  );
  exitCode = 64;
}

void _export(List<TuningDef> defs) {
  File(_templatePath)
    ..createSync(recursive: true)
    ..writeAsStringSync(exportTemplateJson(defs));
  stdout.writeln('wrote $_templatePath (${defs.length} keys)');
  final doc = File(_docPath);
  if (doc.existsSync()) {
    final next = replaceBetween(
      doc.readAsStringSync(),
      _keysStart,
      _keysEnd,
      renderKeyTable(defs),
    );
    if (next == null) {
      stderr.writeln('$_docPath has no key-table markers; table not written');
    } else {
      doc.writeAsStringSync(next);
      stdout.writeln('updated the key table in $_docPath');
    }
  }
}

Future<void> _import(List<String> args) async {
  String? from;
  var project = _defaultProject;
  var dry = false;
  for (var i = 0; i < args.length; i++) {
    switch (args[i]) {
      case '--from':
        from = args[++i];
      case '--project':
        project = args[++i];
      case '--dry-run':
        dry = true;
    }
  }
  final Map<String, dynamic> template = from != null
      ? jsonDecode(File(from).readAsStringSync()) as Map<String, dynamic>
      : await _download(project);
  final result = importDefs(kTuningDefaults, templateValues(template));
  for (final k in result.changed) {
    stdout.writeln('changed  $k');
  }
  for (final k in result.rejected) {
    stdout.writeln('REJECTED $k (does not parse; default kept)');
  }
  for (final k in result.unknown) {
    stdout.writeln('unknown  $k (not in tuning_defaults.dart; ignored)');
  }
  if (dry) {
    stdout.writeln('dry run: ${result.changed.length} changed, nothing written');
    return;
  }
  File(_defaultsPath).writeAsStringSync(renderDefaultsFile(result.defs));
  stdout.writeln(
    'rewrote $_defaultsPath (${result.changed.length} changed). '
    'Review the diff and run flutter test.',
  );
}

/// The live template through the Remote Config REST API, with the owner's
/// gcloud sign-in (user token first, then application-default credentials).
Future<Map<String, dynamic>> _download(String project) async {
  final token = await _token();
  final client = HttpClient();
  try {
    final req = await client.getUrl(
      Uri.parse(
        'https://firebaseremoteconfig.googleapis.com/v1/projects/$project/remoteConfig',
      ),
    );
    req.headers
      ..set('Authorization', 'Bearer $token')
      ..set('x-goog-user-project', project)
      ..set('Accept-Encoding', 'identity');
    final res = await req.close();
    final body = await res.transform(utf8.decoder).join();
    if (res.statusCode != 200) {
      throw HttpException('Remote Config GET ${res.statusCode}: $body');
    }
    return jsonDecode(body) as Map<String, dynamic>;
  } finally {
    client.close();
  }
}

Future<String> _token() async {
  for (final cmd in [
    ['auth', 'print-access-token'],
    ['auth', 'application-default', 'print-access-token'],
  ]) {
    try {
      final r = await Process.run('gcloud', cmd);
      final t = (r.stdout as String).trim();
      if (r.exitCode == 0 && t.isNotEmpty) return t;
    } on ProcessException {
      break;
    }
  }
  throw StateError(
    'No Google sign-in: run `gcloud auth login` (the first console import '
    'is an owner task otherwise, PRD-2.3 §15.5).',
  );
}
